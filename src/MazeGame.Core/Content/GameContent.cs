namespace MazeGame.Core;

/// <summary>
/// ===  YOUR CONTENT GOES HERE  ===
/// Add tiles and entities in the two methods below. Both the game and the level editor call
/// <see cref="RegisterAll"/> at start-up, so whatever you register shows up in the editor palette and in levels.
///
/// TILE      TileRegistry.Register(new TileDef("lava", "Lava") { Frames = new[] { "custom/lava_1.png", "custom/lava_2.png" }, Fps = 5, Deadly = true });
/// ENTITY    EntityRegistry.Register(new EntityType("slime", "Slime", (def, editor) => new Slime(def)) { Texture = "custom/slime.png" });
///
/// Images are .png or .svg files inside the assets folder. Level files then simply say "lava" or { "type": "slime" }.
/// </summary>
public static class GameContent
{
    private static bool _done;

    public static void RegisterAll()
    {
        if (_done) return;
        _done = true;
        RegisterTiles();
        RegisterTilesets();
        RegisterEntities();
        RegisterOverworldTiles();
    }

    private static void RegisterTiles()
    {
        // Shape: "" walk through, "#" solid, "=" one-way platform, "L" ladder
        TileRegistry.Register(new TileDef("lava", "Lava", shape: "", category: "Hazards")
        {
            Frames = new[] { "custom/lava_1.png", "custom/lava_2.png", "custom/lava_3.png" },   // animated tile
            Fps = 5,
            Deadly = true,                       // kills the player on touch
        });

        TileRegistry.Register(new TileDef("stone_brick", "Stone brick", shape: "#", category: "Custom blocks")
        {
            Texture = "custom/stone_brick.png",
        });

        TileRegistry.Register(new TileDef("gem_ruby", "Ruby", category: "Custom blocks")
        {
            Frames = new[] { "custom/ruby_1.png", "custom/ruby_2.png" },
            Fps = 3,
            GemValue = 25,                       // collectible, worth 25 coins
        });
    }

    // ---- three extra tilesets (art generated by tools/make_tilesets.py)

    private static void Solid(string id, string name, string cat, string tex)
        => TileRegistry.Register(new TileDef(id, name, shape: "#", category: cat) { Texture = $"custom/{tex}.png" });

    private static void Platform(string id, string name, string cat, string tex)
        => TileRegistry.Register(new TileDef(id, name, shape: "=", category: cat) { Texture = $"custom/{tex}.png" });

    private static void Decor(string id, string name, string cat, string tex, bool deadly = false)
        => TileRegistry.Register(new TileDef(id, name, shape: "", category: cat) { Texture = $"custom/{tex}.png", Deadly = deadly });

    private static void Gem(string id, string name, string cat, string prefix, int value)
        => TileRegistry.Register(new TileDef(id, name, category: cat)
        {
            Frames = new[] { $"custom/{prefix}_1.png", $"custom/{prefix}_2.png" },
            Fps = 3,
            GemValue = value,
        });

    private static void RegisterTilesets()
