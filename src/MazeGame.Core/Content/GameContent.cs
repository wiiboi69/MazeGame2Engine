    }
}

/// <summary>
/// Example custom entity: a slime that walks like the original walkers (it hops up one-tile ledges and
/// turns at walls) and kills the player on touch.
/// </summary>
public sealed class Slime : Entity
{
    public Slime(EntityDef def)
    {
        Kind = EntityKind.Custom;
        PlaceInCell(def.X, def.Y, halfWidth: 13, halfHeight: 16);
        SizePct = 200;                                       // a 16x16 image drawn at 200% fills one cell
        Dir = def.Get("direction", "right").StartsWith("l", StringComparison.OrdinalIgnoreCase) ? -90 : 90;
    }

    public override void Update(World w)
    {
        if (Kind == EntityKind.Flip) { base.Update(w); return; }      // bumped from below: let the engine tumble it away
        StepWalker(w);                                                // gravity + walking + ledge hopping
        if (Kind == EntityKind.Flip) return;
        if (w.Mode == WorldMode.Playing && TouchesPlayer(w, 0.8)) w.KillPlayer();
    }
}


/// <summary>Invisible rectangle (visible in the editor) that fires the script events enter / exit / use.</summary>
public sealed class Zone : Entity
{
    private readonly string _id;
    private readonly double _hw, _hh;
    private bool _inside;

    public Zone(EntityDef def, bool editor)
    {
        Kind = EntityKind.Custom;
        _id = def.Get("id");
        int cw = Math.Max(1, def.GetInt("w", 1)), ch = Math.Max(1, def.GetInt("h", 1));
        _hw = cw * 16; _hh = ch * 16;
        Width = _hw; Height = _hh;
        X = def.X * 32 + _hw;
        Y = def.Y * 32 + _hh;
        SizePct = 200;
        Visible = editor;
    }

    public override void Update(World w)
    {
        if (w.Mode != WorldMode.Playing) return;
        bool now = TouchesPlayer(w, 1.0);
        if (now && !_inside) w.FireEvent("enter", _id);
        if (!now && _inside) w.FireEvent("exit", _id);
        if (now && w.Input.UsePressed) w.FireEvent("use", _id);
        _inside = now;
    }
}

/// <summary>A visible object the player activates with the use key; fires the script event "use".</summary>
public sealed class ScriptButton : Entity
{
    private readonly string _id;

    public ScriptButton(EntityDef def)
    {
        Kind = EntityKind.Custom;
        _id = def.Get("id");
        PlaceInCell(def.X, def.Y, halfWidth: 12, halfHeight: 12);
        SizePct = 200;
    }

    public override void Update(World w)
    {
        if (w.Mode == WorldMode.Playing && TouchesPlayer(w, 1.0) && w.Input.UsePressed)
        {
            w.PlaySound("pop");
            w.FireEvent("use", _id);
        }
    }
}
