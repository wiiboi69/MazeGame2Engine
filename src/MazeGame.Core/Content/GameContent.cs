    // ---- the overworld's own 2D tileset (art: tools/make_overworld_tiles.py, assets/overworld/)

    private static void Ow(string id, string name, string cat, bool walk = true, double speed = 1, int frames = 0)
        => OverworldTileRegistry.Register(new OverworldTileDef(id, name)
        {
            Category = cat,
            Walkable = walk,
