"""Converts src/MazeGame.Core/Generated/BuiltinTiles.g.cs into cpp/core/BuiltinTiles.gen.inc (C++)."""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "src/MazeGame.Core/Generated/BuiltinTiles.g.cs").read_text(encoding="utf-8")
out = ["// generated by cpp/tools/gen_builtin_tiles.py from BuiltinTiles.g.cs - do not edit\n"]
pat = re.compile(r'Add\(new TileDef\(("[^"]*"), ("[^"]*"), ("[^"]*"), ("[^"]*"), ("[^"]*"), ("[^"]*")\)\s*(\{[^}]*\})?\s*,\s*(\d+)\);')
n = 0
for m in pat.finditer(src):
    a = m.groups()
    props = []
    if a[6]:
        for p in re.findall(r'(\w+) = ([^,}]+)', a[6]):
            k, v = p[0], p[1].strip()
            if v == "true": v = "true"
            props.append(f"d->{k[0].lower()+k[1:]} = {v};")
    out.append(f"{{ auto* d = new TileDef({a[0]}, {a[1]}, {a[2]}, {a[3]}, {a[4]}, {a[5]}); {' '.join(props)} TileRegistry::registerBuiltin(d, {a[7]}); }}\n")
    n += 1
(root / "cpp/core/BuiltinTiles.gen.inc").write_text("".join(out), encoding="utf-8")
print("tiles:", n)
